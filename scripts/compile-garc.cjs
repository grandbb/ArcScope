const fs = require('node:fs');
const path = require('node:path');
const solc = require('solc');
const root = path.join(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'contracts/ArcGarc.sol'), 'utf8');
const input = {
  language: 'Solidity', sources: { 'ArcGarc.sol': { content: source } },
  settings: { optimizer: { enabled: true, runs: 200 }, evmVersion: 'paris',
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object'] } } },
};
const output = JSON.parse(solc.compile(JSON.stringify(input)));
for (const error of output.errors ?? []) {
  if (error.severity === 'error') throw Error(error.formattedMessage);
  process.stderr.write(error.formattedMessage);
}
const contract = output.contracts['ArcGarc.sol'].ArcGarc;
const artifact = `// Generated by npm run contracts:compile. Do not edit.\n// Solidity ${solc.version()}, optimizer 200 runs, EVM paris.\nexport const garcAbi = ${JSON.stringify(contract.abi, null, 2)} as const;\nexport const garcBytecode = "0x${contract.evm.bytecode.object}" as const;\nexport const garcRuntimeBytecode = "0x${contract.evm.deployedBytecode.object}" as const;\n`;
const destinations = [[path.join(root, 'lib/generated/garc.ts'), artifact], [path.join(root, 'public/contracts/ArcGarc.sol'), source],
  [path.join(root, 'public/contracts/ArcGarc.compiler-input.json'), JSON.stringify(input, null, 2) + '\n']];
for (const [file, content] of destinations) {
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== content.replace(/\r\n/g, '\n')) throw Error(`Stale contract artifact: ${file}`);
  } else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, content); }
}
process.stdout.write(`ArcGarc compiled: ${contract.evm.bytecode.object.length / 2} bytes; artifacts ${process.argv.includes('--check') ? 'verified' : 'written'}.\n`);
